/**
 * Turns the vendored BIP-39 list into the module the app ships.
 *
 * Run with `just link-words` after changing the list, which should be never:
 * a device that generated words from one list and a device that reads them
 * with another would not agree on the mailbox, let alone the key.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE = fileURLToPath(new URL('../wordlist/bip39-english.txt', import.meta.url));
const TARGET = fileURLToPath(new URL('../app/src/lib/link-words.ts', import.meta.url));
const EXPECTED_SHA = '2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda';

const raw = await readFile(SOURCE);
const sha = createHash('sha256').update(raw).digest('hex');
if (sha !== EXPECTED_SHA) {
  throw new Error(`word list is not the one this build expects: ${sha}`);
}

const words = raw.toString('utf8').trim().split('\n').map((word) => word.trim());
if (words.length !== 2048) throw new Error(`expected 2048 words, got ${words.length}`);

// Wrapped by hand rather than left to a formatter, so the file stays readable
// in a diff and Prettier has nothing to argue with.
const lines = [];
for (let at = 0; at < words.length; at += 8) {
  lines.push(`  ${words.slice(at, at + 8).join(' ')}`);
}

await writeFile(
  TARGET,
  `/**
 * The words a device link is spoken in.
 *
 * Generated by \`scripts/build-link-words.mjs\` from \`wordlist/bip39-english.txt\`;
 * see \`wordlist/PROVENANCE.md\` for where it comes from and why this list rather
 * than the one the word game plays against. Do not edit by hand, and do not
 * reorder: a word's position is its value, so a device generating words against
 * one order and a device reading them against another would not agree on the
 * key or on where the bundle was left.
 */

/** Exactly 2048, so each word carries 11 bits. */
export const LINK_WORDS: readonly string[] = \`
${lines.join('\n')}
\`
  .trim()
  .split(/\\s+/);
`,
);

console.log(`wrote ${words.length} words to ${TARGET}`);
